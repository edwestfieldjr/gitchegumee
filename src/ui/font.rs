#[derive(Resource, Clone)]
pub struct FontImage(pub Handle<Image>);

/// RGBA8 pixels of the glyph sheet, with the sheet size.
fn sheet_pixels() -> (Vec<u8>, u32, u32) {
    let rows = (GLYPHS.len() as u32).div_ceil(COLUMNS);
    let (cell_w, cell_h) = (CELL_W as u32, CELL_H as u32);
    let (width, height) = (COLUMNS * cell_w, rows * cell_h);
    let mut pixels = vec![0u8; (width * height * 4) as usize];
    for (index, glyph) in GLYPHS.iter().enumerate() {
        let (cx, cy) = (index as u32 % COLUMNS, index as u32 / COLUMNS);
        for (y, row) in glyph.iter().enumerate() {
            for x in 0..5u32 {
                if row & (0x10 >> x) != 0 {
                    let px = cx * cell_w + x;
                    let py = cy * cell_h + y as u32;
                    let offset = ((py * width + px) * 4) as usize;
                    pixels[offset..offset + 4].copy_from_slice(&[255, 255, 255, 255]);
                }
            }
        }
    }
    (pixels, width, height)
}

pub fn build_font_image() -> Image {
    let (pixels, width, height) = sheet_pixels();
    Image::new(
        Extent3d {
            width,
            height,
            depth_or_array_layers: 1,
        },
        TextureDimension::D2,
        pixels,
        TextureFormat::Rgba8UnormSrgb,
        RenderAssetUsages::RENDER_WORLD,
    )
}

/// The sheet rectangle of a character. Lowercase folds to uppercase, and
/// anything the font lacks falls back to a space.
pub fn glyph_rect(character: char) -> Rect {
    let upper = character.to_ascii_uppercase();
    let index = if upper.is_ascii() && (u32::from(upper) as usize) >= usize::from(FIRST) {
        let offset = upper as usize - usize::from(FIRST);
        if offset < GLYPHS.len() { offset } else { 0 }
    } else {
        0
    };
    let x = (index as u32 % COLUMNS) as f32 * CELL_W;
    let y = (index as u32 / COLUMNS) as f32 * CELL_H;
    Rect::new(x, y, x + CELL_W, y + CELL_H)
}

/// Break text into lines of at most `columns`, keeping explicit newlines.
pub fn wrap(text: &str, columns: usize) -> Vec<String> {
    let mut lines = Vec::new();
    for paragraph in text.split('\n') {
        let mut line = String::new();
        for word in paragraph.split_whitespace() {
            let needed = line.len() + word.len() + usize::from(!line.is_empty());
            if needed > columns && !line.is_empty() {
                lines.push(std::mem::take(&mut line));
            }
            if !line.is_empty() {
                line.push(' ');
            }
            line.push_str(word);
        }
        lines.push(line);
    }
    lines
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn wrap_respects_width_and_newlines() {
        let lines = wrap("one two three\nfour", 7);
        assert_eq!(lines, ["one two", "three", "four"]);
    }

    #[test]
    fn wrap_keeps_blank_lines() {
        assert_eq!(wrap("a\n\nb", 10), ["a", "", "b"]);
    }

    #[test]
    fn lowercase_folds_to_uppercase() {
        assert_eq!(glyph_rect('a'), glyph_rect('A'));
    }

    #[test]
    fn unknown_characters_render_as_space() {
        assert_eq!(glyph_rect('~'), glyph_rect(' '));
        assert_eq!(glyph_rect('\u{00e9}'), glyph_rect(' '));
    }
}
